const dictionaries: Record<Locale, Record<UiKey, string>> = { en, zh };

export function translate(locale: Locale, key: UiKey, variables: Record<string, string | number> = {}) {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match
  ));
}

export function getTrackCopy(locale: Locale, name: string) {
  const keys = {
    Acquire: ["acquire", "acquireDetail"],
    Revisit: ["revisit", "revisitDetail"],
    Interpret: ["interpret", "interpretDetail"],
  } as const;
  const selected = keys[name as keyof typeof keys];
  return selected
    ? { name: translate(locale, selected[0]), detail: translate(locale, selected[1]) }
    : { name, detail: "" };
}

export function getMemoryTierLabel(locale: Locale, tier: string) {
  const key = tier.toLowerCase() as "dormant" | "trace" | "familiar" | "rooted";
  return key in dictionaries[locale] ? translate(locale, key) : tier;
}
